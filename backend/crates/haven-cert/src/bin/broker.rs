//! `haven-cert-broker` — issue the broker's own certificate from the device CA.
//!
//! The broker needs a server certificate to offer TLS, and the devices need to trust the CA
//! that signed it. Using the same CA for both is what makes `require_certificate` on the TLS
//! listener meaningful: a device certificate is signed by the CA the broker trusts, and a
//! stranger's is not.
//!
//! ```text
//! cargo run -p haven-cert --bin haven-cert-broker -- .haven/ca deploy/certs localhost
//! ```
//!
//! Writes `server.crt`, `server.key` and a copy of `ca.pem` into the output directory.

use std::path::PathBuf;

use rcgen::{
    CertificateParams, DistinguishedName, DnType, ExtendedKeyUsagePurpose, IsCa, KeyPair,
    KeyUsagePurpose, SanType,
};
use time::OffsetDateTime;

#[tokio::main]
async fn main() -> Result<(), Box<dyn std::error::Error>> {
    let mut args = std::env::args().skip(1);
    let ca_dir = PathBuf::from(args.next().unwrap_or_else(|| ".haven/ca".into()));
    let out_dir = PathBuf::from(args.next().unwrap_or_else(|| "deploy/certs".into()));
    let hostname = args.next().unwrap_or_else(|| "localhost".into());
    // A device on the same Wi-Fi dials the machine's LAN address, not `localhost` — and
    // `WiFiClientSecure` checks the SAN, so a certificate without it fails the handshake with
    // nothing but "connection refused" to go on. The address is passed in because it is a DHCP
    // lease, not a fact about the machine.
    let lan_ip: Option<std::net::IpAddr> = args.next().and_then(|ip| ip.parse().ok());

    let ca = haven_cert::Ca::load_or_create(&ca_dir).await?;
    std::fs::create_dir_all(&out_dir)?;

    // Only this one certificate needs hostname SANs: it is the one a client verifies against
    // the address it dialled.
    let key = KeyPair::generate()?;
    let mut params = CertificateParams::default();
    let mut dn = DistinguishedName::new();
    dn.push(DnType::CommonName, hostname.clone());
    params.distinguished_name = dn;
    params.is_ca = IsCa::ExplicitNoCa;
    params.key_usages = vec![
        KeyUsagePurpose::DigitalSignature,
        KeyUsagePurpose::KeyEncipherment,
    ];
    params.extended_key_usages = vec![ExtendedKeyUsagePurpose::ServerAuth];
    let mut sans = vec![
        SanType::DnsName(hostname.clone().try_into()?),
        SanType::DnsName("localhost".to_string().try_into()?),
        SanType::IpAddress("127.0.0.1".parse()?),
    ];
    if let Some(ip) = lan_ip {
        sans.push(SanType::IpAddress(ip));
    }
    params.subject_alt_names = sans;

    let now = OffsetDateTime::now_utc();
    params.not_before = now - time::Duration::minutes(5);
    params.not_after = now + time::Duration::days(825);

    // Re-derive the issuer from the CA material on disk: the signing key and the certificate
    // the clients trust have to be the same pair, and this is the only place that can drift.
    let ca_params = rcgen::CertificateParams::from_ca_cert_pem(ca.certificate_pem())?;
    let ca_key = KeyPair::from_pem(ca.key_pem())?;
    let issuer = ca_params.self_signed(&ca_key)?;

    let cert = params.signed_by(&key, &issuer, &ca_key)?;

    std::fs::write(out_dir.join("server.crt"), cert.pem())?;
    std::fs::write(out_dir.join("server.key"), key.serialize_pem())?;
    std::fs::write(out_dir.join("ca.pem"), ca.certificate_pem())?;

    // A private key next to a compose file is one `git add -A` from being published.
    std::fs::write(
        out_dir.join(".gitignore"),
        "# Generated by `make broker-tls`; never commit a private key.\n*\n",
    )?;

    println!(
        "wrote {}/server.crt, server.key and ca.pem for {hostname}{}",
        out_dir.display(),
        lan_ip.map(|ip| format!(" and {ip}")).unwrap_or_default()
    );
    Ok(())
}
